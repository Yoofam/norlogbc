function ErrorComponent({ error, reset }: { error: Error; reset: () => void }) {
  console.error(error);
  const router = useRouter();
  useEffect(() => {
    reportLovableError(error, { boundary: "tanstack_root_error_component" });
  }, [error]);

  return (
    <div className="flex min-h-screen items-center justify-center bg-background px-4">
      <div className="max-w-md text-center">
        <h1 className="font-display text-xl font-bold uppercase tracking-wider text-foreground">
          This page didn't load
        </h1>
        <p className="mt-2 text-sm text-muted-foreground">
          Something went wrong on our end. You can try refreshing or head back home.
        </p>
        <div className="mt-6 flex flex-wrap justify-center gap-2">
          <button
            onClick={() => { router.invalidate(); reset(); }}
            className="border-2 border-foreground bg-accent px-4 py-2 font-display text-sm font-bold uppercase tracking-wider text-accent-foreground"
          >
            Try again
          </button>
          <a href="/" className="border-2 border-foreground bg-background px-4 py-2 font-display text-sm font-bold uppercase tracking-wider">
            Go home
          </a>
        </div>
      </div>
    </div>
  );
}

